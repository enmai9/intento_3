-- préstamos: usuarios leen sus préstamos; admins leen todos
create policy "loans_select_own_or_admin"
on public.loans
for select
using (
  auth.uid() = user_id
  or exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.role = 'admin'
  )
);

create policy "loans_insert_own"
on public.loans
for insert
with check (auth.uid() = user_id);

create policy "loans_update_admin_only"
on public.loans
for update
using (
  exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.role = 'admin'
  )
)
with check (
  exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.role = 'admin'
  )
);

